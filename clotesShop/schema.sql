-- Clothes Shop catalog (PostgreSQL 14+)
-- สินค้า 150 ชิ้น: เสื้อ 50, กางเกง 50, เดรส 50
-- คำอธิบายอยู่ใน seed.sql  รูปอยู่ใน images.sql
-- ไม่มีตารางคะแนน

BEGIN;

-- ---------------------------------------------------------------------------
-- products: เสื้อผ้า 1 แถวต่อ 1 ชิ้น  id กำหนดเองให้ตรงกับหน้าร้าน
-- ---------------------------------------------------------------------------
CREATE TABLE products (
    id           BIGINT        PRIMARY KEY,
    name         VARCHAR(255)  NOT NULL,
    title        VARCHAR(255)  NOT NULL,
    category     VARCHAR(20)   NOT NULL CHECK (category IN ('เสื้อ', 'กางเกง', 'เดรส')),
    price        INTEGER       NOT NULL CHECK (price >= 0),
    stock        INTEGER       NOT NULL CHECK (stock >= 0),
    description  TEXT          NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_products_category    ON products (category);
CREATE INDEX idx_products_name_lower  ON products (lower(name));

-- ---------------------------------------------------------------------------
-- product_sizes: ไซส์ของสินค้าหนึ่งชิ้น เรียงตาม position
-- ---------------------------------------------------------------------------
CREATE TABLE product_sizes (
    product_id  BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    size        VARCHAR(20)  NOT NULL,
    position    SMALLINT     NOT NULL CHECK (position >= 0),
    PRIMARY KEY (product_id, size),
    UNIQUE (product_id, position)
);

-- ---------------------------------------------------------------------------
-- product_images: รูป 1 ใบต่อ 1 สินค้า  URL ห้ามซ้ำ
-- ข้อมูลรูปแยกอยู่ไฟล์ images.sql
-- ---------------------------------------------------------------------------
CREATE TABLE product_images (
    product_id  BIGINT  PRIMARY KEY REFERENCES products (id) ON DELETE CASCADE,
    image_url   TEXT    NOT NULL,
    UNIQUE (image_url)
);

-- ---------------------------------------------------------------------------
-- members: สมาชิกของร้าน บทบาทตรงกับหน้าร้าน buyer / seller / admin
-- password_hash เป็น bcrypt ห้ามเก็บรหัสผ่านตรง ๆ
-- ---------------------------------------------------------------------------
CREATE TABLE members (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(255)  NOT NULL,
    password_hash  VARCHAR(255)  NOT NULL,
    display_name   VARCHAR(50)   NOT NULL CHECK (char_length(btrim(display_name)) >= 1),
    role           VARCHAR(10)   NOT NULL DEFAULT 'buyer' CHECK (role IN ('buyer', 'seller', 'admin')),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX uq_members_email ON members (lower(email));

-- สินค้าแต่ละชิ้นเป็นของร้านผู้ขายคนหนึ่ง
ALTER TABLE products
    ADD COLUMN seller_id BIGINT REFERENCES members (id);

-- ---------------------------------------------------------------------------
-- ข้อมูลที่ต้องแยกตามสมาชิก เลขสมาชิกมาจากตั๋ว ไม่รับจากหน้าเว็บ
-- ---------------------------------------------------------------------------
CREATE TABLE wishlists (
    member_id   BIGINT      NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    product_id  BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (member_id, product_id)
);

CREATE TABLE reviews (
    id          BIGSERIAL    PRIMARY KEY,
    product_id  BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    member_id   BIGINT       NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    rating      SMALLINT     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment     TEXT         NOT NULL CHECK (char_length(btrim(comment)) >= 1),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (member_id, product_id)
);

CREATE INDEX idx_reviews_product ON reviews (product_id, created_at DESC);

CREATE TABLE carts (
    member_id   BIGINT      NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    product_id  BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    size        VARCHAR(20) NOT NULL,
    quantity    INTEGER     NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (member_id, product_id, size)
);

CREATE TABLE orders (
    id         BIGSERIAL    PRIMARY KEY,
    buyer_id   BIGINT       NOT NULL REFERENCES members (id),
    total      INTEGER      NOT NULL CHECK (total >= 0),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE order_items (
    id           BIGSERIAL    PRIMARY KEY,
    order_id     BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id   BIGINT       REFERENCES products (id) ON DELETE SET NULL,
    seller_id    BIGINT       NOT NULL REFERENCES members (id),
    product_name VARCHAR(255) NOT NULL,
    size         VARCHAR(20)  NOT NULL,
    quantity     INTEGER      NOT NULL CHECK (quantity > 0),
    unit_price   INTEGER      NOT NULL CHECK (unit_price >= 0),
    status       VARCHAR(30)  NOT NULL DEFAULT 'รอการจัดส่ง',
    tracking_no  VARCHAR(50)  NOT NULL DEFAULT ''
);

CREATE INDEX idx_order_items_seller ON order_items (seller_id);

CREATE TABLE disputes (
    id          BIGSERIAL    PRIMARY KEY,
    product_id  BIGINT       REFERENCES products (id) ON DELETE SET NULL,
    buyer_id    BIGINT       NOT NULL REFERENCES members (id),
    reason      TEXT         NOT NULL CHECK (char_length(btrim(reason)) >= 1),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved    BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE chat_messages (
    id          BIGSERIAL    PRIMARY KEY,
    product_id  BIGINT       NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    buyer_id    BIGINT       NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    sender      VARCHAR(10)  NOT NULL CHECK (sender IN ('user', 'seller')),
    body        TEXT         NOT NULL CHECK (char_length(btrim(body)) >= 1),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_chat_thread ON chat_messages (product_id, buyer_id, created_at);

COMMIT;
